//! `gport record`: docs/port/record.md, its generator and its parser.
//!
//! The record is regenerated from the map, the rulings, the dispositions and
//! the frozen ledger. Its kept blocks are hand-maintained: each run copies a
//! kept block's body from the existing record, so text written inside one is
//! never lost. The scanner below is also the parser `check-slice` reads through.

use std::collections::{BTreeMap, BTreeSet};
use std::fs;
use std::io::Write;
use std::path::{Path, PathBuf};

use anyhow::{Context, bail};
use fancy_regex::Regex;
use serde_json::Value;

use crate::map::Map;
use crate::rows::{self, Row, Selectors};
use crate::{DISPOSITIONS_DIR, FROZEN_LEDGER_PATH, MAP_PATH, RECORD_PATH, RULINGS_PATH};

#[cfg(test)]
mod tests;

const SEAM_CONTRACT: &str = "seam-contract";
const REGISTRATION: &str = "registration";
const MEMORY_RULINGS: &str = "memory-rulings";
const KNOWN_BAD: &str = "known-bad";
const FROZEN_HEADING: &str = "### Frozen files";
const OPEN_PREFIX: &str = "<!-- gport:kept ";
const END_PREFIX: &str = "<!-- gport:end ";
const MARKER_SUFFIX: &str = " -->";
const NONE_RECORDED: &str = "none recorded";
const INTRO: &str = "Generated by `gport record` from docs/port/map-v2.json, docs/port/rulings.md, docs/port/dispositions/*.json and docs/port/ledger.md. Each kept block is hand-maintained text between a `gport:kept <name>` line and its matching `gport:end <name>` line. A run copies a kept block's body unchanged, starts a new block empty, and refuses rather than drop a block whose name the layout has no place for. Everything outside the kept blocks is regenerated.";

/// A kept block body by name. A name that is absent starts empty.
type Bodies = BTreeMap<String, Vec<String>>;

/// Run `gport record`: regenerate docs/port/record.md under `root`.
///
/// Writes nothing and returns `Ok(false)` when an existing kept block is
/// duplicated, malformed, or has no place in the new layout. Each refusal is
/// printed to `out`, one per line.
pub fn run(root: &Path, out: &mut dyn Write) -> anyhow::Result<bool> {
    let inputs = Inputs::load(root)?;
    let path = root.join(RECORD_PATH);
    let scan = scan_kept(&read_existing(&path)?);

    let mut refusals = scan.problems.clone();
    let mut counts: BTreeMap<&str, usize> = BTreeMap::new();
    for block in &scan.blocks {
        *counts.entry(block.name.as_str()).or_default() += 1;
    }
    refusals.extend(
        counts
            .iter()
            .filter(|(_, count)| **count > 1)
            .map(|(name, count)| format!("kept block {name} appears {count} times")),
    );

    let mut bodies: Bodies = BTreeMap::new();
    for block in &scan.blocks {
        bodies
            .entry(block.name.clone())
            .or_insert_with(|| block.body.clone());
    }
    let (text, placed) = render(&inputs, &bodies)?;
    let unplaced: BTreeSet<&str> = scan
        .blocks
        .iter()
        .map(|block| block.name.as_str())
        .filter(|name| !placed.contains(*name))
        .collect();
    refusals.extend(
        unplaced
            .into_iter()
            .map(|name| format!("kept block {name} has no place in the new layout")),
    );

    if !refusals.is_empty() {
        for refusal in &refusals {
            writeln!(out, "refused: {refusal}")?;
        }
        return Ok(false);
    }
    write_atomic(&path, &text)?;
    writeln!(out, "wrote {RECORD_PATH}")?;
    Ok(true)
}

/// The paths under the `### Frozen files` heading of the frozen seam contract.
///
/// Reads the seam-contract kept block of `record`: each "- `path`" line after a
/// `### Frozen files` heading is a path, up to the next heading. A record with
/// no such block yields an empty list.
pub fn frozen_files(record: &str) -> Vec<String> {
    scan_kept(record)
        .blocks
        .iter()
        .filter(|block| block.name == SEAM_CONTRACT)
        .flat_map(|block| frozen_paths(&block.body))
        .collect()
}

/// The lines of the `found:<chunk id>` kept block of `record`, verbatim.
///
/// A missing block yields an empty list. When the name is duplicated, the lines
/// of every copy are returned in file order.
pub fn found_work_lines(record: &str, chunk_id: &str) -> Vec<String> {
    let name = format!("found:{chunk_id}");
    scan_kept(record)
        .blocks
        .into_iter()
        .filter(|block| block.name == name)
        .flat_map(|block| block.body)
        .collect()
}

/// Everything the record is generated from, read once per run.
struct Inputs {
    map: Map,
    rulings: String,
    dispositions: Vec<Disposition>,
    /// Each chunk's owned row keys, in ledger order.
    owned: BTreeMap<String, Vec<String>>,
}

impl Inputs {
    fn load(root: &Path) -> anyhow::Result<Self> {
        let map = Map::load(root)?;
        reject_markers_in(MAP_PATH, &map.raw)?;
        let mut seen = BTreeSet::new();
        for chunk in &map.chunks {
            if !seen.insert(chunk.id.as_str()) {
                bail!("the map lists chunk {} more than once", chunk.id);
            }
        }
        let rulings = read_input(root, RULINGS_PATH)?;
        reject_markers(RULINGS_PATH, &rulings)?;
        let dispositions = load_dispositions(root)?;
        let ledger = read_input(root, FROZEN_LEDGER_PATH)?;
        let selectors = Selectors::compile(&map.chunks);
        if !selectors.bad.is_empty() {
            bail!(
                "ledger selectors do not compile:\n{}",
                selectors.bad.join("\n")
            );
        }
        let owned = owned_by_chunk(&selectors, &rows::rows(&ledger))?;
        Ok(Self {
            map,
            rulings,
            dispositions,
            owned,
        })
    }
}

/// One row of the open-node dispositions table.
struct Disposition {
    reference: String,
    disposition: String,
    target: String,
    rationale: String,
}

/// Every disposition of docs/port/dispositions/*.json, files sorted by name.
fn load_dispositions(root: &Path) -> anyhow::Result<Vec<Disposition>> {
    let dir = root.join(DISPOSITIONS_DIR);
    let entries = fs::read_dir(&dir).with_context(|| format!("cannot read {}", dir.display()))?;
    let mut files: Vec<PathBuf> = Vec::new();
    for entry in entries {
        let path = entry
            .with_context(|| format!("cannot list {}", dir.display()))?
            .path();
        if path.extension().is_some_and(|ext| ext == "json") && path.is_file() {
            files.push(path);
        }
    }
    files.sort();

    let mut all = Vec::new();
    for file in &files {
        let bytes = fs::read(file).with_context(|| format!("cannot read {}", file.display()))?;
        let value: Value = serde_json::from_slice(&bytes)
            .with_context(|| format!("{} is not valid JSON", file.display()))?;
        let source = file.strip_prefix(root).unwrap_or(file.as_path());
        reject_markers_in(&source.display().to_string(), &value)?;
        for item in
            array_field(&value, "dispositions").with_context(|| format!("in {}", file.display()))?
        {
            all.push(Disposition {
                reference: str_field(item, "ref")?.to_owned(),
                disposition: str_field(item, "disposition")?.to_owned(),
                target: str_field(item, "target")?.to_owned(),
                rationale: str_field(item, "rationale")?.to_owned(),
            });
        }
    }
    Ok(all)
}

/// Each chunk's owned row keys: the keys its selectors own and no other chunk does. A selector that
/// fails to run is an input error.
///
/// Owners are resolved once per row, so the cost is rows times selectors, not
/// chunks times rows.
fn owned_by_chunk(
    selectors: &Selectors,
    ledger_rows: &[Row],
) -> anyhow::Result<BTreeMap<String, Vec<String>>> {
    let mut owned: BTreeMap<String, Vec<String>> = BTreeMap::new();
    for row in ledger_rows {
        let owners = selectors.try_owners(&row.key)?;
        if let [owner] = owners.as_slice() {
            owned
                .entry((*owner).to_owned())
                .or_default()
                .push(row.key.clone());
        }
    }
    Ok(owned)
}

/// The record text, and the names of the kept blocks it places.
fn render(inputs: &Inputs, bodies: &Bodies) -> anyhow::Result<(String, BTreeSet<String>)> {
    let mut doc = Doc {
        lines: Vec::new(),
        bodies,
        placed: BTreeSet::new(),
    };
    let raw = &inputs.map.raw;
    doc.heading("# Port record");
    doc.para(INTRO);
    direction(&mut doc, raw)?;
    reference_base(&mut doc, raw)?;
    chunk_protocol(&mut doc, raw)?;
    doc.heading("## Registration protocol");
    doc.kept(REGISTRATION);
    decisions(&mut doc, raw)?;
    doc.heading("## Rulings");
    rulings(&mut doc, &inputs.rulings);
    doc.heading("## Rulings from memory");
    doc.kept(MEMORY_RULINGS);
    open_node_dispositions(&mut doc, &inputs.dispositions);
    chunks(&mut doc, inputs);
    doc.heading("## Frozen seam contract");
    doc.kept(SEAM_CONTRACT);
    doc.heading("## Known-bad index");
    doc.kept(KNOWN_BAD);
    doc.heading("## Found Work");
    for chunk in &inputs.map.chunks {
        doc.heading(&format!("### {}", chunk.id));
        doc.kept(&format!("found:{}", chunk.id));
    }
    Ok(doc.finish())
}

fn direction(doc: &mut Doc<'_>, raw: &Value) -> anyhow::Result<()> {
    doc.heading("## Direction");
    doc.para(str_field(raw, "summary")?);
    doc.para(str_field(raw, "angle")?);
    doc.para(str_field(raw, "cutover_model")?);
    doc.para(str_field(raw, "python_strategy")?);
    doc.para(str_field(raw, "branching")?);
    let live = field(raw, "live_checkout_constraints")?;
    doc.para(str_field(live, "intro")?);
    doc.bullets(&string_list(live, "items")?);
    doc.para(str_field(raw, "rollback_and_packaging")?);
    Ok(())
}

fn reference_base(doc: &mut Doc<'_>, raw: &Value) -> anyhow::Result<()> {
    let sha = cut_sha(str_field(raw, "summary")?)?;
    doc.heading("## Reference base");
    doc.para(&format!("Cut SHA: `{sha}`, named by the map summary."));
    Ok(())
}

fn chunk_protocol(doc: &mut Doc<'_>, raw: &Value) -> anyhow::Result<()> {
    let protocol = field(raw, "chunk_protocol")?;
    doc.heading("## Chunk protocol");
    for (index, step) in string_list(protocol, "steps")?.iter().enumerate() {
        doc.line(format!("{}. {step}", index + 1));
    }
    doc.blank();
    doc.para(str_field(protocol, "note")?);
    Ok(())
}

fn decisions(doc: &mut Doc<'_>, raw: &Value) -> anyhow::Result<()> {
    doc.heading("## Decisions");
    for decision in array_field(raw, "decisions")? {
        doc.heading(&format!(
            "### {}: {}",
            str_field(decision, "id")?,
            str_field(decision, "question")?
        ));
        doc.para(&format!(
            "**Default:** {}",
            str_field(decision, "recommended_default")?
        ));
        doc.para(&format!(
            "**Rationale:** {}",
            str_field(decision, "rationale")?
        ));
        doc.para(&format!(
            "**Resolved by:** {}",
            optional_str(decision, "resolved_by")?
        ));
    }
    Ok(())
}

/// docs/port/rulings.md verbatim, with each heading demoted two levels outside code fences.
fn rulings(doc: &mut Doc<'_>, body: &str) {
    let mut in_fence = false;
    for line in body.lines() {
        let trimmed = line.trim_start();
        if trimmed.starts_with("```") || trimmed.starts_with("~~~") {
            in_fence = !in_fence;
            doc.line(line);
        } else if in_fence {
            doc.line(line);
        } else {
            doc.line(demote(line).unwrap_or_else(|| line.to_owned()));
        }
    }
    doc.blank();
}

fn open_node_dispositions(doc: &mut Doc<'_>, dispositions: &[Disposition]) {
    doc.heading("## Open-node dispositions");
    doc.line("| Ref | Disposition | Target | Rationale |");
    doc.line("| --- | --- | --- | --- |");
    for item in dispositions {
        doc.line(format!(
            "| {} | {} | {} | {} |",
            cell(&item.reference),
            cell(&item.disposition),
            cell(&item.target),
            cell(&item.rationale)
        ));
    }
    doc.blank();
}

fn chunks(doc: &mut Doc<'_>, inputs: &Inputs) {
    doc.heading("## Chunks");
    for chunk in &inputs.map.chunks {
        doc.heading(&format!("### {}: {}", chunk.id, chunk.title));
        doc.line(format!("- kind: `{}`", chunk.kind));
        doc.line(format!("- depends on: {}", depends_on(&chunk.depends_on)));
        doc.line(format!("- python edits: {}", or_none(&chunk.python_edits)));
        doc.blank();
        doc.heading("#### Owned rows");
        for key in inputs.owned.get(&chunk.id).into_iter().flatten() {
            doc.line(format!("- `{key}`"));
        }
        doc.blank();
        doc.heading("#### Debt not to port");
        doc.kept(&format!("debt:{}", chunk.id));
    }
}

/// Accumulates the record's lines and tracks which kept blocks it has placed.
struct Doc<'a> {
    lines: Vec<String>,
    bodies: &'a Bodies,
    placed: BTreeSet<String>,
}

impl Doc<'_> {
    fn line(&mut self, text: impl Into<String>) {
        self.lines.push(text.into());
    }

    /// A blank line, unless the record is empty or already ends in one.
    fn blank(&mut self) {
        if self.lines.last().is_some_and(|last| !last.is_empty()) {
            self.lines.push(String::new());
        }
    }

    fn heading(&mut self, text: &str) {
        self.line(text);
        self.blank();
    }

    fn para(&mut self, text: &str) {
        for line in text.lines() {
            self.line(line);
        }
        self.blank();
    }

    fn bullets(&mut self, items: &[&str]) {
        for item in items {
            self.line(format!("- {item}"));
        }
        self.blank();
    }

    /// A kept block: its markers around the body it carried in, or none.
    fn kept(&mut self, name: &str) {
        self.line(format!("{OPEN_PREFIX}{name}{MARKER_SUFFIX}"));
        if let Some(body) = self.bodies.get(name) {
            self.lines.extend(body.iter().cloned());
        }
        self.line(format!("{END_PREFIX}{name}{MARKER_SUFFIX}"));
        self.placed.insert(name.to_owned());
        self.blank();
    }

    fn finish(mut self) -> (String, BTreeSet<String>) {
        while self.lines.last().is_some_and(String::is_empty) {
            self.lines.pop();
        }
        let mut output = self.lines.join("\n");
        output.push('\n');
        (output, self.placed)
    }
}

/// One kept block of a record: its name and the lines between its markers.
#[derive(Debug, Clone, PartialEq, Eq)]
struct KeptBlock {
    name: String,
    body: Vec<String>,
}

/// The kept blocks of a record in file order, and each malformed marker found.
#[derive(Debug, Default)]
struct Scan {
    blocks: Vec<KeptBlock>,
    problems: Vec<String>,
}

enum Marker<'a> {
    Open(&'a str),
    End(&'a str),
}

/// A line without its trailing carriage return, so a CRLF record reads like an LF one.
fn text_of(line: &str) -> &str {
    line.strip_suffix('\r').unwrap_or(line)
}

/// A kept-block marker, which counts only when it is the whole line.
fn marker(line: &str) -> Option<Marker<'_>> {
    let line = text_of(line);
    if let Some(name) = line
        .strip_prefix(OPEN_PREFIX)
        .and_then(|rest| rest.strip_suffix(MARKER_SUFFIX))
    {
        return (!name.is_empty()).then_some(Marker::Open(name));
    }
    let name = line.strip_prefix(END_PREFIX)?.strip_suffix(MARKER_SUFFIX)?;
    (!name.is_empty()).then_some(Marker::End(name))
}

/// Scan every kept block of `text`. Malformed markers are recorded as problems.
///
/// Lines split on `\n` alone, so a body keeps any carriage return it carries.
fn scan_kept(text: &str) -> Scan {
    let mut scan = Scan::default();
    let mut open: Option<KeptBlock> = None;
    for line in text.split_terminator('\n') {
        match marker(line) {
            None => {
                if let Some(block) = open.as_mut() {
                    block.body.push(line.to_owned());
                }
            }
            Some(Marker::Open(name)) => {
                if let Some(block) = open.take() {
                    scan.problems
                        .push(format!("kept block {} is never closed", block.name));
                    scan.blocks.push(block);
                }
                open = Some(KeptBlock {
                    name: name.to_owned(),
                    body: Vec::new(),
                });
            }
            Some(Marker::End(name)) => match open.take() {
                Some(block) if block.name == name => scan.blocks.push(block),
                Some(block) => {
                    scan.problems.push(format!(
                        "kept block {} is closed by the end marker of {name}",
                        block.name
                    ));
                    scan.blocks.push(block);
                }
                None => scan.problems.push(format!(
                    "end marker of kept block {name} has no start marker"
                )),
            },
        }
    }
    if let Some(block) = open.take() {
        scan.problems
            .push(format!("kept block {} is never closed", block.name));
        scan.blocks.push(block);
    }
    scan
}

/// The frozen paths in one seam-contract body.
fn frozen_paths(body: &[String]) -> Vec<String> {
    let mut paths = Vec::new();
    let mut listing = false;
    for line in body.iter().map(|line| text_of(line)) {
        if line == FROZEN_HEADING {
            listing = true;
        } else if heading_level(line).is_some() {
            listing = false;
        } else if listing {
            paths.extend(list_path(line));
        }
    }
    paths
}

/// The path of a "- `path`" line, or None for any other line.
fn list_path(line: &str) -> Option<String> {
    let path = line.strip_prefix("- `")?.strip_suffix('`')?;
    (!path.is_empty() && !path.contains('`')).then(|| path.to_owned())
}

/// The level of an ATX heading (one to six `#`, then a space or the end), or None.
fn heading_level(line: &str) -> Option<usize> {
    let level = line.bytes().take_while(|byte| *byte == b'#').count();
    let rest = &line[level..];
    ((1..=6).contains(&level) && (rest.is_empty() || rest.starts_with(' '))).then_some(level)
}

/// The heading line raised by two levels, capped at six, or None for a non-heading.
fn demote(line: &str) -> Option<String> {
    let level = heading_level(line)?;
    let rest = &line[level..];
    Some(format!("{}{rest}", "#".repeat((level + 2).min(6))))
}

/// The cut SHA named after "cut SHA" in the map summary.
fn cut_sha(summary: &str) -> anyhow::Result<&str> {
    let pattern = Regex::new(r"cut SHA.*?\b([0-9a-f]{7,40})\b")?;
    let found = pattern
        .captures(summary)?
        .and_then(|captures| captures.get(1))
        .context("the map summary names no cut SHA")?;
    Ok(found.as_str())
}

/// A table cell on one line, with pipes escaped.
fn cell(value: &str) -> String {
    value.replace(['\r', '\n'], " ").replace('|', "\\|")
}

fn depends_on(ids: &[String]) -> String {
    if ids.is_empty() {
        return "none".to_owned();
    }
    ids.iter()
        .map(|id| format!("`{id}`"))
        .collect::<Vec<_>>()
        .join(", ")
}

fn or_none(text: &str) -> &str {
    if text.is_empty() { NONE_RECORDED } else { text }
}

fn read_input(root: &Path, relative: &str) -> anyhow::Result<String> {
    let path = root.join(relative);
    fs::read_to_string(&path).with_context(|| format!("cannot read {}", path.display()))
}

/// Refuse `text` when one of its lines is shaped like a kept-block marker.
///
/// A generated record copies such text, and a copied marker would open a second
/// block of the same name, so the input is an error rather than a rewrite.
fn reject_markers(source: &str, text: &str) -> anyhow::Result<()> {
    match text
        .split_terminator('\n')
        .find(|line| marker(line).is_some())
    {
        Some(line) => bail!(
            "{source} holds the kept-block marker `{}`, which a generated record cannot carry",
            text_of(line)
        ),
        None => Ok(()),
    }
}

/// `reject_markers` applied to every string inside a parsed JSON value.
fn reject_markers_in(source: &str, value: &Value) -> anyhow::Result<()> {
    match value {
        Value::String(text) => reject_markers(source, text),
        Value::Array(items) => items
            .iter()
            .try_for_each(|item| reject_markers_in(source, item)),
        Value::Object(fields) => fields
            .values()
            .try_for_each(|item| reject_markers_in(source, item)),
        Value::Null | Value::Bool(_) | Value::Number(_) => Ok(()),
    }
}

/// Replace `path` with `text` through a sibling temp file and a rename, so an
/// interrupted write leaves the existing file whole. A failed write removes its
/// temp file.
fn write_atomic(path: &Path, text: &str) -> anyhow::Result<()> {
    let temp = sibling_temp(path);
    let result = write_synced(&temp, text).and_then(|()| fs::rename(&temp, path));
    if result.is_err() {
        let _ = fs::remove_file(&temp);
    }
    result.with_context(|| format!("cannot write {}", path.display()))
}

/// The temp path beside `path`, unique to this process.
fn sibling_temp(path: &Path) -> PathBuf {
    let name = path
        .file_name()
        .map(|name| name.to_string_lossy())
        .unwrap_or_default();
    path.with_file_name(format!(".{name}.{}.tmp", std::process::id()))
}

/// Create `path` with `text` and flush it to disk.
fn write_synced(path: &Path, text: &str) -> std::io::Result<()> {
    let mut file = fs::File::create(path)?;
    file.write_all(text.as_bytes())?;
    file.sync_all()
}

/// The record as it stands, or empty when none has been written yet.
fn read_existing(path: &Path) -> anyhow::Result<String> {
    match fs::read_to_string(path) {
        Ok(text) => Ok(text),
        Err(error) if error.kind() == std::io::ErrorKind::NotFound => Ok(String::new()),
        Err(error) => Err(error).with_context(|| format!("cannot read {}", path.display())),
    }
}

fn field<'a>(value: &'a Value, key: &str) -> anyhow::Result<&'a Value> {
    value
        .get(key)
        .with_context(|| format!("the map has no `{key}` field"))
}

fn str_field<'a>(value: &'a Value, key: &str) -> anyhow::Result<&'a str> {
    field(value, key)?
        .as_str()
        .with_context(|| format!("`{key}` is not a string"))
}

/// A string field that may be absent or null, rendered as the placeholder when it is.
fn optional_str<'a>(value: &'a Value, key: &str) -> anyhow::Result<&'a str> {
    match value.get(key) {
        None | Some(Value::Null) => Ok(NONE_RECORDED),
        Some(other) => other
            .as_str()
            .with_context(|| format!("`{key}` is not a string or null")),
    }
}

fn array_field<'a>(value: &'a Value, key: &str) -> anyhow::Result<&'a [Value]> {
    field(value, key)?
        .as_array()
        .map(Vec::as_slice)
        .with_context(|| format!("`{key}` is not an array"))
}

fn string_list<'a>(value: &'a Value, key: &str) -> anyhow::Result<Vec<&'a str>> {
    array_field(value, key)?
        .iter()
        .map(|item| {
            item.as_str()
                .with_context(|| format!("`{key}` holds an entry that is not a string"))
        })
        .collect()
}
